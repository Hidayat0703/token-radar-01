// Token Radar, model radar-2: a sealed snapshot goes in, a ranked board comes out.
//
// The board ranks every protocol on the snapshot's watchlist (the floor, never the
// ceiling) plus the strongest pre-token protocols below that floor, which the early
// radar exists to find. A protocol counts as pre-token when its record carries no
// token at all: no market cap, no CoinGecko id, no symbol. Protocols whose token
// already trades are never ranked: their market cap is a fact, not a model, so they
// are set aside and shown with the market's own value.
//
// One function scores every protocol the same way, from the snapshot's own figures
// only:
//
//   base      = tvl_usd x 0.30
//   growth    = clamp(change_7d, -60, 120) per cent
//   growth    = 1 + (growth / 100) x 0.60
//   maturity  = 0.60 + min(age_days, 1095) / 1095 x 0.40   (age unknown: 365 days)
//   breadth   = 1 + 0.04 x min(chains - 1, 5)              (one chain: 1.00, six+: 1.20)
//   implied   = max(1, round(base x growth x maturity x breadth))
//
// What each term means: TVL is the protocol's size today. Seven-day growth is its
// momentum. Age is how long it has run with no token: a protocol that has held value
// for years without issuing one has a larger pent-up claim on a launch than a new
// one. Breadth is how many chains it runs on: a protocol live on more chains has
// more surface for a token to land on. No protocol name is ever special-cased.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them. */
export interface ModelConstants {
  base_multiple: number;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  breadth_per_chain: number;
  breadth_max_chains: number;
}

export const MODEL: ModelConstants = {
  base_multiple: 0.3,
  growth_weight: 0.6,
  growth_floor: -60,
  growth_cap: 120,
  maturity_floor: 0.6,
  maturity_range: 0.4,
  maturity_days: 1095,
  unknown_age_days: 365,
  breadth_per_chain: 0.04,
  breadth_max_chains: 5,
};

/** The model's version label: the dashboard names it. */
export const MODEL_VERSION = 'radar-2';

/** How many pre-token protocols below the watchlist floor the early radar carries, by TVL. */
export const EARLY_ROWS = 200;

/** How many live-token protocols the Live token view carries, by market cap. */
export const LIVE_ROWS = 24;

/** A farm step: the action, what it costs, and how long it takes. */
